function interpolate(template: string, vars?: TVARS): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  );
}

/** 按界面语言取一句键控文案。 */
export function translate(lang: Lang, key: TKey, vars?: TVARS): string {
  return interpolate(lang === "zh" ? zh[key] : en[key], vars);
}

/**
 * Rust 传来的 UiText：键在字典里就按当前语言拼，不在（版本错位）就退回英文后备。
 * 后备总是英文原文，因此字典缺键永远不会把用户扔在一句空话上。
 */
export function translateText(
  lang: Lang,
  key: string,
  vars: TVARS | undefined,
  fallback: string,
): string {
  const dict: Record<string, string> = lang === "zh" ? zh : en;
  const template = dict[key];
  return interpolate(template ?? fallback, vars);
}

/** Rust UiText 的落地：对话流、通知栏、坞里的回执都走这一句。 */
export function renderUiText(lang: Lang, text: UiText): string {
  return translateText(lang, text.key, text.vars, text.fallback);
}
